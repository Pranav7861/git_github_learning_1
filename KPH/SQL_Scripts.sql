CREATE OR REPLACE PROCEDURE KPH_VERTEX_PRD.STAGE.SPNONCORE_MEDISPAN_CODEHANDLER_MISCQUERIES("VREQUESTTYPE" NUMBER(38,0), "VFILELAYOUT" VARCHAR)
RETURNS VARCHAR
LANGUAGE SQL
EXECUTE AS CALLER
AS
$$
DECLARE
    SP_NAME STRING DEFAULT 'MEDISPAN.SPNONCORE_MEDISPAN_CODEHANDLER_MISCQUERIES';
    SP_START_TIME TIMESTAMP_NTZ DEFAULT CURRENT_TIMESTAMP();
BEGIN

    -- ############################################################################################################
    -- REQUEST TYPE 1:
    -- Used to clear staging tables for a specific Medispan file layout.
    -- ############################################################################################################
    IF (VREQUESTTYPE = 1) THEN

        IF (VFILELAYOUT = 'M25') THEN
            TRUNCATE TABLE STAGE.MEDISPANAWPPRICES;
            TRUNCATE TABLE STAGE.MEDISPANCMSFULPRICES;
