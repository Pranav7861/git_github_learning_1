CREATE OR REPLACE PROCEDURE KPH_VERTEX_PRD.VERTEX.GETSYSTEMSETTINGS()
RETURNS TABLE ("EMAILADDRESS" VARCHAR, "SERVER" VARCHAR, "DIRECTORY" VARCHAR, "CRMINSTANCE" VARCHAR)
LANGUAGE SQL
EXECUTE AS OWNER
AS
$$
DECLARE
    V_EMAILADDRESS VARCHAR DEFAULT NULL;
    V_SERVER       VARCHAR DEFAULT NULL;
    V_DIRECTORY    VARCHAR DEFAULT NULL;
    V_CRMINSTANCE  VARCHAR DEFAULT NULL;
    RES            RESULTSET;
BEGIN
----------------------------------------------------------------------------
-- Get EmailAddress from CRM.USERS
----------------------------------------------------------------------------
    SELECT EMAILADDRESS INTO :V_EMAILADDRESS
    FROM CRM.USERS --Change this to point to CRM schema
    ORDER BY USERNAME
    LIMIT 1;

----------------------------------------------------------------------------
-- Get settings from CRM.SYSTEMSETTINGS
----------------------------------------------------------------------------
    SELECT SERVERNAME, ROOTDIRECTORY, COALESCE(EMAILADDRESS, :V_EMAILADDRESS)
    INTO  :V_SERVER, :V_DIRECTORY, :V_EMAILADDRESS
    FROM VERTEX.SYSTEMSETTINGS;

----------------------------------------------------------------------------
-- Build resultset and return it
----------------------------------------------------------------------------
    RES := (
        SELECT
              :V_EMAILADDRESS AS EMAILADDRESS
            , :V_SERVER       AS SERVER
            , :V_DIRECTORY    AS DIRECTORY
            , :V_CRMINSTANCE  AS CRMINSTANCE
    );

    RETURN TABLE(RES);
END;
$$;

CREATE OR REPLACE PROCEDURE KPH_VERTEX_PRD.VERTEX.SPINSERT_SOURCEFILE("VFILECATEGORYID" NUMBER(38,0), "VPARTNERID" NUMBER(38,0), "VFILENAME" VARCHAR, "VFILEDATE" DATE DEFAULT null, "VIMPORTDATE" TIMESTAMP_NTZ(9) DEFAULT null, "VORIGINALFILENAME" VARCHAR DEFAULT null)
RETURNS NUMBER(38,0)
LANGUAGE SQL
EXECUTE AS CALLER
AS
$$
DECLARE
    SP_NAME STRING DEFAULT 'VERTEX.SPINSERT_SOURCEFILE';
    SP_START_TIME TIMESTAMP_NTZ DEFAULT CURRENT_TIMESTAMP()::TIMESTAMP_NTZ;
    V_SOURCEFILEID NUMBER(38,0);
BEGIN
    BEGIN TRANSACTION;

    -- Get the next key from a sequence
    SELECT VERTEX.SEQ_SOURCEFILES.NEXTVAL
      INTO :V_SOURCEFILEID;

    -- Insert the row
    INSERT INTO VERTEX.SOURCEFILES
    (
        SOURCEFILEID,
        FILECATEGORYID,
        PARTNERID,
        FILENAME,
        FILEDATE,
        IMPORTDATE,
        ORIGINALFILENAME
    )
    VALUES
    (
        :V_SOURCEFILEID,
        :VFILECATEGORYID,
        :VPARTNERID,
        :VFILENAME,
        :VFILEDATE,
        COALESCE(:VIMPORTDATE, CURRENT_TIMESTAMP()::TIMESTAMP_NTZ),
        :VORIGINALFILENAME
    );

    COMMIT;

    -- Audit log
    INSERT INTO METRICS.SP_CALL
    (
        SP_NAME,
        SP_START_TIME,
        SP_USER,
        SP_END_TIME
    )
    VALUES
    (
        :SP_NAME,
        :SP_START_TIME,
        CURRENT_USER(),
        CURRENT_TIMESTAMP()::TIMESTAMP_NTZ
    );

    RETURN V_SOURCEFILEID;

EXCEPTION
    WHEN OTHER THEN
        ROLLBACK;

        INSERT INTO STAGE.SP_CALL
        (
            SP_NAME,
            SP_START_TIME,
            SP_USER,
            SP_END_TIME
        )
        VALUES
        (
            :SP_NAME || ' - FAILED',
            :SP_START_TIME,
            CURRENT_USER(),
            CURRENT_TIMESTAMP()::TIMESTAMP_NTZ
        );

        RAISE;
END;
$$;

CREATE OR REPLACE PROCEDURE KPH_VERTEX_PRD.VERTEX.SP_MANAGE_SOURCEFILE("VREQUESTTYPE" NUMBER(38,0), "VFILENAME" VARCHAR DEFAULT null, "VFILECATEGORYID" NUMBER(38,0) DEFAULT null, "VSOURCEFILEID" NUMBER(38,0) DEFAULT null, "VRECORDCOUNT" NUMBER(38,0) DEFAULT null)
RETURNS NUMBER(1,0)
LANGUAGE SQL
EXECUTE AS CALLER
AS
$$
DECLARE
    SP_NAME STRING DEFAULT 'SP_MANAGE_SOURCEFILE';
    SP_START_TIME TIMESTAMP_NTZ DEFAULT CURRENT_TIMESTAMP()::TIMESTAMP_NTZ;
    V_EXISTS_COUNT BOOLEAN DEFAULT 0;
    V_RESULT VARIANT DEFAULT NULL;
BEGIN
    BEGIN TRANSACTION;

    -- =========================================================================================
    -- REQUEST TYPE 1
    -- Check whether the source file already exists for the supplied file category.
    -- =========================================================================================
    IF (VREQUESTTYPE = 1) THEN

        SELECT COUNT(1)
          INTO :V_EXISTS_COUNT
          FROM VERTEX.SOURCEFILES
         WHERE FILENAME = :VFILENAME
           AND FILECATEGORYID = :VFILECATEGORYID;

        V_RESULT := OBJECT_CONSTRUCT(
            'STATUS', 'SUCCESS',
            'REQUEST_TYPE', 1,
            'RECORD_COUNT', V_EXISTS_COUNT
        );

    -- =========================================================================================
    -- REQUEST TYPE 2
    -- Update record count in SOURCEFILES.
    -- =========================================================================================
    ELSEIF (VREQUESTTYPE = 2) THEN

        UPDATE VERTEX.SOURCEFILES
           SET RECORDCOUNT = COALESCE(:VRECORDCOUNT, 0)
         WHERE SOURCEFILEID = :VSOURCEFILEID;

        V_RESULT := OBJECT_CONSTRUCT(
            'STATUS', 'SUCCESS',
            'REQUEST_TYPE', 2,
            'SOURCE_FILE_ID', VSOURCEFILEID
        );

    -- =========================================================================================
    -- REQUEST TYPE 3
    -- Delete child rows first, then parent row.
    -- =========================================================================================
    ELSEIF (VREQUESTTYPE = 3) THEN

        DELETE FROM VERTEX.PROCESS_STATUSBYSOURCEFILE
         WHERE SOURCEFILEID = :VSOURCEFILEID;

        DELETE FROM VERTEX.SOURCEFILES
         WHERE SOURCEFILEID = :VSOURCEFILEID;

        V_RESULT := OBJECT_CONSTRUCT(
            'STATUS', 'SUCCESS',
            'REQUEST_TYPE', 3,
            'SOURCE_FILE_ID', VSOURCEFILEID
        );

    -- =========================================================================================
    -- REQUEST TYPE 4
    -- Update record count in COPAY.SOURCEFILES.
    -- =========================================================================================
    ELSEIF (VREQUESTTYPE = 4) THEN

        UPDATE VERTEX.copay_SOURCEFILES
           SET RECORDCOUNT = COALESCE(:VRECORDCOUNT, 0)
         WHERE SOURCEFILEID = :VSOURCEFILEID;

        V_RESULT := OBJECT_CONSTRUCT(
            'STATUS', 'SUCCESS',
            'REQUEST_TYPE', 4,
            'SOURCE_FILE_ID', VSOURCEFILEID
        );

    -- =========================================================================================
    -- INVALID REQUEST TYPE
    -- =========================================================================================
    ELSE

        V_RESULT := OBJECT_CONSTRUCT(
            'STATUS', 'FAILED',
            'MESSAGE', 'Invalid VREQUESTTYPE. Valid values are 1, 2, 3, and 4.'
        );

    END IF;

    COMMIT;

    -- =========================================================================================
    -- AUDIT LOG
    -- =========================================================================================
    INSERT INTO METRICS.SP_CALL
    (
        SP_NAME,
        SP_START_TIME,
        SP_USER,
        SP_END_TIME
    )
    VALUES
    (
        :SP_NAME,
        :SP_START_TIME,
        CURRENT_USER(),
        CURRENT_TIMESTAMP()
    );

    RETURN IFF(V_EXISTS_COUNT, 1, 0);
	
	--RETURN V_EXISTS_COUNT;

EXCEPTION
    WHEN OTHER THEN
        ROLLBACK;

        -- Best-effort audit entry for failures using the existing SP_CALL table design.
        INSERT INTO VERTEX.SP_CALL
        (
            SP_NAME,
            SP_START_TIME,
            SP_USER,
            SP_END_TIME
        )
        VALUES
        (
            :SP_NAME || ' - FAILED',
            :SP_START_TIME,
            CURRENT_USER(),
            CURRENT_TIMESTAMP()
        );

        RAISE;
END;
$$;

