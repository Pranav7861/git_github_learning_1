CREATE OR REPLACE PROCEDURE KPH_VERTEX_PRD.MEDISPAN.SPNONCORE_MEDISPAN_CODEHANDLER("VSOURCEFILEID" NUMBER(38,0), "VFILELAYOUT" VARCHAR)
RETURNS VARCHAR
LANGUAGE SQL
EXECUTE AS OWNER
AS
$$
DECLARE
    SP_START_TIME TIMESTAMP_LTZ DEFAULT CURRENT_TIMESTAMP();
    SP_NAME STRING DEFAULT 'Medispan.spNonCore_Medispan_Codehandler';
BEGIN

    -- ============================================================
    -- Main Logic
    -- ============================================================

    IF (vFileLayout = 'M25TCRF') THEN
        CALL Medispan.spNonCore_Medispan_Codehandler_M25TCRF(:vSourceFileID);

    ELSEIF (vFileLayout = 'M25MOD') THEN
        CALL Medispan.spNonCore_Medispan_Codehandler_M25MOD(:vSourceFileID);

    ELSEIF (vFileLayout = 'M25GPPC') THEN
        CALL Medispan.spNonCore_Medispan_Codehandler_M25GPPC(:vSourceFileID);

    ELSEIF (vFileLayout = 'M25NMOD') THEN
        CALL Medispan.spNonCore_Medispan_Codehandler_M25NMOD(:vSourceFileID);

    ELSEIF (vFileLayout = 'M25GPRR') THEN
        CALL Medispan.spNonCore_Medispan_Codehandler_M25GPRR(:vSourceFileID);
		
	ELSEIF (vFileLayout = 'M25DICT') THEN
        CALL Medispan.SPNONCORE_MEDISPAN_CODEHANDLER_M25DICT(:vSourceFileID);
	
	ELSEIF (vFileLayout = 'M25VAL') THEN
        CALL Medispan.SPNONCORE_MEDISPAN_CODEHANDLER_M25VAL(:vSourceFileID);

    ELSEIF (vFileLayout = 'M25') THEN
        CALL Medispan.spNonCore_Medispan_Codehandler_M25();

    END IF;

    -- ============================================================
    -- Logging
    -- ============================================================

    INSERT INTO METRICS.SP_CALL  
    (SP_NAME, SP_START_TIME, SP_USER, SP_END_TIME)
    VALUES (:SP_NAME, :SP_START_TIME, CURRENT_USER(), CURRENT_TIMESTAMP());

    RETURN 'SUCCESS';

-- ============================================================
-- Exception Handling
-- ============================================================

EXCEPTION
    WHEN OTHER THEN
        -- Log failure
        INSERT INTO METRICS.SP_CALL  
        (SP_NAME, SP_START_TIME, SP_USER, SP_END_TIME)
        VALUES (:SP_NAME, :SP_START_TIME, CURRENT_USER(), CURRENT_TIMESTAMP());

        RETURN 'FAILED: ' || SQLERRM;

END;
$$;

